class VectorPDF:
    """Pure-Python vector PDF 1.4 document builder with zero external dependencies."""

    def __init__(self, title="Hypatian Observability Report", subtitle=""):
        self.title = title
        self.subtitle = subtitle
        self.pages = []
        self.current_stream = []
        self.new_page()

    def new_page(self):
        if self.current_stream:
            self.pages.append("".join(self.current_stream))
            self.current_stream = []
        # Page header banner (Dark slate navy)
        self.draw_rect(0, 742, 612, 50, fill_rgb=(0.06, 0.09, 0.16))
        self.draw_text(30, 764, "HYPATIAN HOMELAB OBSERVABILITY", font="F2", size=13, fill_rgb=(0.58, 0.64, 0.72))
        self.draw_text(30, 749, self.title.upper(), font="F2", size=10, fill_rgb=(1, 1, 1))
        date_str = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        self.draw_text(420, 756, f"Generated: {date_str}", font="F1", size=8, fill_rgb=(0.7, 0.75, 0.8))

        # Thin accent bar (Emerald green)
        self.draw_rect(0, 739, 612, 3, fill_rgb=(0.06, 0.72, 0.51))

    def draw_footer(self, page_num, total_pages):
        self.draw_rect(30, 36, 552, 1, fill_rgb=(0.88, 0.91, 0.94))
        self.draw_text(30, 24, "Confidential &bull; Hypatian Kubernetes Homelab &bull; Generated by reporting@hypatian.io", font="F1", size=8, fill_rgb=(0.5, 0.55, 0.6))
        self.draw_text(520, 24, f"Page {page_num} of {total_pages}", font="F1", size=8, fill_rgb=(0.5, 0.55, 0.6))

    def draw_rect(self, x, y, w, h, fill_rgb=None, stroke_rgb=None):
        cmd = []
        if fill_rgb:
            cmd.append(f"{fill_rgb[0]:.3f} {fill_rgb[1]:.3f} {fill_rgb[2]:.3f} rg")
        if stroke_rgb:
            cmd.append(f"{stroke_rgb[0]:.3f} {stroke_rgb[1]:.3f} {stroke_rgb[2]:.3f} RG")
        cmd.append(f"{x:.1f} {y:.1f} {w:.1f} {h:.1f} re")
        if fill_rgb and stroke_rgb:
            cmd.append("B")
        elif fill_rgb:
            cmd.append("f")
        elif stroke_rgb:
            cmd.append("S")
        self.current_stream.append(" ".join(cmd) + "\n")

    def draw_text(self, x, y, text, font="F1", size=10, fill_rgb=(0, 0, 0)):
        safe = (
            str(text)
            .replace("\\", "\\\\")
            .replace("(", "\\(")
            .replace(")", "\\)")
            .encode("latin-1", "replace")
            .decode("latin-1")
        )
        cmd = [
            f"{fill_rgb[0]:.3f} {fill_rgb[1]:.3f} {fill_rgb[2]:.3f} rg",
            "BT",
            f"/{font} {size} Tf",
            f"{x:.1f} {y:.1f} Td",
            f"({safe}) Tj",
            "ET\n",
        ]
        self.current_stream.append(" ".join(cmd))

    def draw_card(self, x, y, w, h, title, value, subtitle="", border_rgb=(0.8, 0.83, 0.88), val_rgb=(0.06, 0.09, 0.16)):
        self.draw_rect(x, y, w, h, fill_rgb=(0.97, 0.98, 0.99), stroke_rgb=border_rgb)
        self.draw_text(x + 10, y + h - 16, title.upper(), font="F2", size=8, fill_rgb=(0.4, 0.45, 0.52))
        self.draw_text(x + 10, y + h - 34, str(value), font="F2", size=15, fill_rgb=val_rgb)
        if subtitle:
            self.draw_text(x + 10, y + 8, subtitle, font="F1", size=7, fill_rgb=(0.45, 0.5, 0.58))

    def draw_table(self, x, y, widths, headers, rows, header_bg=(0.06, 0.09, 0.16), header_fg=(1, 1, 1)):
        row_h = 18
        cur_y = y
        # Draw header
        total_w = sum(widths)
        self.draw_rect(x, cur_y - row_h, total_w, row_h, fill_rgb=header_bg)
        col_x = x
        for i, h in enumerate(headers):
            self.draw_text(col_x + 5, cur_y - 13, str(h), font="F2", size=8, fill_rgb=header_fg)
            col_x += widths[i]
        cur_y -= row_h

        # Draw rows
        for idx, row in enumerate(rows):
            bg = (0.96, 0.97, 0.99) if idx % 2 == 1 else (1.0, 1.0, 1.0)
            self.draw_rect(x, cur_y - row_h, total_w, row_h, fill_rgb=bg, stroke_rgb=(0.88, 0.9, 0.93))
            col_x = x
            for i, val in enumerate(row):
                self.draw_text(col_x + 5, cur_y - 13, str(val)[:45], font="F1", size=7.5, fill_rgb=(0.1, 0.15, 0.2))
                col_x += widths[i]
            cur_y -= row_h
        return cur_y

    def build_bytes(self):
        if self.current_stream:
            self.pages.append("".join(self.current_stream))
            self.current_stream = []

        total_p = len(self.pages)
        # Rebuild each page with footer
        final_pages = []
        for i, page_str in enumerate(self.pages):
            self.current_stream = [page_str]
            self.draw_footer(i + 1, total_p)
            final_pages.append("".join(self.current_stream))
        self.pages = final_pages

        objects = []
        objects.append(b"<< /Type /Catalog /Pages 2 0 R >>")
        page_refs = [f"{i+3} 0 R" for i in range(len(self.pages))]
        objects.append(f"<< /Type /Pages /Kids [{chr(32).join(page_refs)}] /Count {len(self.pages)} >>".encode("ascii"))

        N = len(self.pages)
        for i in range(N):
            stream_obj_idx = 3 + N + i
            objects.append(
                f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> /F2 << /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >> /F3 << /Type /Font /Subtype /Type1 /BaseFont /Courier >> >> >> /Contents {stream_obj_idx} 0 R >>".encode(
                    "ascii"
                )
            )

        for content in self.pages:
            c_bytes = content.encode("latin-1")
            objects.append(f"<< /Length {len(c_bytes)} >>\nstream\n".encode("ascii") + c_bytes + b"\nendstream")

        out = [b"%PDF-1.4\n"]
        xref = [0]
        offset = len(out[0])
        for i, obj in enumerate(objects):
            xref.append(offset)
            block = f"{i+1} 0 obj\n".encode("ascii") + obj + b"\nendobj\n"
            out.append(block)
            offset += len(block)

        startxref = offset
        out.append(f"xref\n0 {len(xref)}\n0000000000 65535 f \n".encode("ascii"))
        for off in xref[1:]:
            out.append(f"{off:010d} 00000 n \n".encode("ascii"))
        out.append(f"trailer\n<< /Size {len(xref)} /Root 1 0 R >>\nstartxref\n{startxref}\n%%EOF\n".encode("ascii"))
        return b"".join(out)


